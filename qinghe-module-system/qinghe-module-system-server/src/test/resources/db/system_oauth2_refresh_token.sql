CREATE TABLE `system_oauth2_refresh_token` (
    `id` bigint NOT NULL AUTO_INCREMENT COMMENT '刷新令牌记录编号',
    `refresh_token` varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '不透明刷新凭据，禁止日志输出，不可用于普通接口认证',
    `user_id` bigint NOT NULL COMMENT '用户编号，身份还须结合租户和用户类型',
    `user_type` tinyint NOT NULL COMMENT '用户类型：1会员，2后台用户',
    `client_id` varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '服务端验证的应用标识',
    `scopes` json NOT NULL COMMENT '授权范围字符串数组，空范围写JSON数组[]',
    `expires_time` datetime(6) NOT NULL COMMENT '过期时间，统一时间约定后由服务端赋值',
    `revoked_time` datetime(6) DEFAULT NULL COMMENT '主动撤销时间，NULL表示未主动撤销',
    `tenant_id` bigint NOT NULL COMMENT '可信租户归属，0仅供明确平台身份，不默认赋值',
    `creator` varchar(64) NOT NULL DEFAULT '' COMMENT '创建者标识，由服务端维护',
    `create_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间',
    `updater` varchar(64) NOT NULL DEFAULT '' COMMENT '更新者标识，由服务端维护',
    `update_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间',
    `deleted` bit(1) NOT NULL DEFAULT b'0' COMMENT '逻辑删除，不替代主动撤销状态',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_refresh_token_value` (`refresh_token`),
    KEY `idx_refresh_token_subject` (`tenant_id`, `user_type`, `user_id`, `client_id`),
    KEY `idx_refresh_token_expires` (`expires_time`, `id`),
    CONSTRAINT `chk_refresh_token_value` CHECK (CHAR_LENGTH(`refresh_token`) > 0),
    CONSTRAINT `chk_refresh_token_user` CHECK (`user_id` > 0),
    CONSTRAINT `chk_refresh_token_user_type` CHECK (`user_type` IN (1, 2)),
    CONSTRAINT `chk_refresh_token_client` CHECK (CHAR_LENGTH(`client_id`) > 0),
    CONSTRAINT `chk_refresh_token_tenant` CHECK (`tenant_id` >= 0),
    CONSTRAINT `chk_refresh_token_scopes` CHECK (JSON_TYPE(`scopes`) = 'ARRAY')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='OAuth2刷新令牌';
