CREATE TABLE promotion_coupon_template (
 id BIGINT NOT NULL AUTO_INCREMENT,
 name VARCHAR(64) NOT NULL,
 description VARCHAR(500) NOT NULL DEFAULT '',
 status TINYINT NOT NULL DEFAULT 0,
 total_count INT NOT NULL,
 take_limit_count INT NOT NULL,
 take_type TINYINT NOT NULL,
 use_price INT NOT NULL,
 product_scope TINYINT NOT NULL,
 product_scope_values JSON NOT NULL,
 validity_type TINYINT NOT NULL,
 valid_start_time DATETIME(6) NULL,
 valid_end_time DATETIME(6) NULL,
 fixed_start_term INT NULL,
 fixed_end_term INT NULL,
 discount_type TINYINT NOT NULL,
 discount_percent INT NULL,
 discount_price INT NULL,
 discount_limit_price INT NULL,
 take_count INT NOT NULL DEFAULT 0,
 use_count INT NOT NULL DEFAULT 0,
 auth_version BIGINT NOT NULL DEFAULT 0,
 tenant_id BIGINT NOT NULL,
 creator VARCHAR(64) NOT NULL DEFAULT '',
 updater VARCHAR(64) NOT NULL DEFAULT '',
 create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 deleted BIT(1) NOT NULL DEFAULT b'0',
 PRIMARY KEY(id),
 KEY idx_coupon_template_status(tenant_id,status,id),
 KEY idx_coupon_template_take(tenant_id,take_type,status,id),
 CONSTRAINT ck_coupon_template_1 CHECK(tenant_id>0 AND auth_version>=0),
 CONSTRAINT ck_coupon_template_2 CHECK(use_price BETWEEN 0 AND 2000000000),
 CONSTRAINT ck_coupon_template_3 CHECK(product_scope IN(1,2,3) AND JSON_TYPE(product_scope_values)='ARRAY' AND ((product_scope=1 AND JSON_LENGTH(product_scope_values)=0) OR (product_scope IN(2,3) AND JSON_LENGTH(product_scope_values) BETWEEN 1 AND 200))),
 CONSTRAINT ck_coupon_template_4 CHECK((discount_type=1 AND discount_price IS NOT NULL AND discount_price BETWEEN 1 AND 2000000000 AND discount_percent IS NULL AND discount_limit_price IS NULL) OR (discount_type=2 AND discount_price IS NULL AND discount_percent IS NOT NULL AND discount_limit_price IS NOT NULL AND discount_percent BETWEEN 1 AND 99 AND discount_limit_price BETWEEN 1 AND 2000000000)),
 CONSTRAINT ck_coupon_template_5 CHECK(take_type IN(1,2)),
 CONSTRAINT ck_coupon_template_6 CHECK(status IN(0,1)),
 CONSTRAINT ck_coupon_template_7 CHECK((total_count=-1 OR total_count BETWEEN 1 AND 2000000000) AND (take_limit_count=-1 OR take_limit_count BETWEEN 1 AND 2000000000) AND (total_count=-1 OR take_limit_count=-1 OR take_limit_count<=total_count)),
 CONSTRAINT ck_coupon_template_8 CHECK( take_count BETWEEN 0 AND 2000000000 AND (total_count=-1 OR take_count<=total_count) AND use_count BETWEEN 0 AND take_count),
 CONSTRAINT ck_coupon_template_9 CHECK((validity_type=1 AND valid_start_time IS NOT NULL AND valid_end_time IS NOT NULL AND valid_start_time<valid_end_time AND fixed_start_term IS NULL AND fixed_end_term IS NULL) OR (validity_type=2 AND valid_start_time IS NULL AND valid_end_time IS NULL AND fixed_start_term IS NOT NULL AND fixed_end_term IS NOT NULL AND fixed_start_term=0 AND fixed_end_term BETWEEN 1 AND 3650))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE promotion_coupon (
 id BIGINT NOT NULL AUTO_INCREMENT,
 template_id BIGINT NOT NULL,
 name VARCHAR(64) NOT NULL,
 status TINYINT NOT NULL DEFAULT 1,
 user_id BIGINT NOT NULL,
 take_type TINYINT NOT NULL,
 use_price INT NOT NULL,
 valid_start_time DATETIME(6) NOT NULL,
 valid_end_time DATETIME(6) NOT NULL,
 product_scope TINYINT NOT NULL,
 product_scope_values JSON NOT NULL,
 discount_type TINYINT NOT NULL,
 discount_percent INT NULL,
 discount_price INT NULL,
 discount_limit_price INT NULL,
 use_order_id BIGINT NULL,
 use_time DATETIME(6) NULL,
 auth_version BIGINT NOT NULL DEFAULT 0,
 template_version BIGINT NOT NULL,
 grant_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 locked_order_id BIGINT NULL,
 locked_time DATETIME(6) NULL,
 invalidated_time DATETIME(6) NULL,
 tenant_id BIGINT NOT NULL,
 creator VARCHAR(64) NOT NULL DEFAULT '',
 updater VARCHAR(64) NOT NULL DEFAULT '',
 create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 deleted BIT(1) NOT NULL DEFAULT b'0',
 PRIMARY KEY(id),
 UNIQUE KEY uk_coupon_grant(tenant_id,user_id,grant_key),
 UNIQUE KEY uk_coupon_used_order(tenant_id,use_order_id),
 UNIQUE KEY uk_coupon_locked_order(tenant_id,locked_order_id),
 KEY idx_coupon_user(tenant_id,user_id,status,id),
 KEY idx_coupon_template_user(tenant_id,template_id,user_id,id),
 KEY idx_coupon_expiry(tenant_id,status,valid_end_time,id),
 CONSTRAINT ck_coupon_1 CHECK(tenant_id>0 AND auth_version>=0),
 CONSTRAINT ck_coupon_2 CHECK(use_price BETWEEN 0 AND 2000000000),
 CONSTRAINT ck_coupon_3 CHECK(product_scope IN(1,2,3) AND JSON_TYPE(product_scope_values)='ARRAY' AND ((product_scope=1 AND JSON_LENGTH(product_scope_values)=0) OR (product_scope IN(2,3) AND JSON_LENGTH(product_scope_values) BETWEEN 1 AND 200))),
 CONSTRAINT ck_coupon_4 CHECK((discount_type=1 AND discount_price IS NOT NULL AND discount_price BETWEEN 1 AND 2000000000 AND discount_percent IS NULL AND discount_limit_price IS NULL) OR (discount_type=2 AND discount_price IS NULL AND discount_percent IS NOT NULL AND discount_limit_price IS NOT NULL AND discount_percent BETWEEN 1 AND 99 AND discount_limit_price BETWEEN 1 AND 2000000000)),
 CONSTRAINT ck_coupon_5 CHECK(take_type IN(1,2)),
 CONSTRAINT ck_coupon_6 CHECK(user_id>0 AND template_id>0 AND template_version>=0),
 CONSTRAINT ck_coupon_7 CHECK(status IN(1,2,3,4,5)),
 CONSTRAINT ck_coupon_8 CHECK(valid_start_time<valid_end_time),
 CONSTRAINT ck_coupon_9 CHECK(CHAR_LENGTH(grant_key) BETWEEN 8 AND 128),
 CONSTRAINT ck_coupon_10 CHECK((use_order_id IS NULL OR use_order_id>0) AND (locked_order_id IS NULL OR locked_order_id>0)),
 CONSTRAINT ck_coupon_11 CHECK((use_order_id IS NULL)=(use_time IS NULL) AND (locked_order_id IS NULL)=(locked_time IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
