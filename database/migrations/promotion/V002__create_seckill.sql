CREATE TABLE promotion_seckill_activity (
 id bigint NOT NULL AUTO_INCREMENT COMMENT '活动ID',
 tenant_id bigint NOT NULL COMMENT '可信租户ID',
 activity_no varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '公开活动号，区分大小写',
 name varchar(60) NOT NULL COMMENT '活动名称',
 product_spu_id bigint NOT NULL COMMENT '商品SPU逻辑关联',
 start_time datetime(3) NOT NULL COMMENT '开始UTC，含',
 end_time datetime(3) NOT NULL COMMENT '结束UTC，不含',
 single_limit int unsigned NOT NULL COMMENT '每单上限',
 member_limit int unsigned NOT NULL COMMENT '整场会员上限，含处理中与已支付',
 status tinyint unsigned NOT NULL DEFAULT 0 COMMENT '0草稿10准备20发布30停止40清算50结束60发布失败',
 version bigint unsigned NOT NULL DEFAULT 0 COMMENT '配置和状态栅栏版本',
 generation int unsigned NOT NULL DEFAULT 0 COMMENT '每次重新发布递增，区分划拨代次',
 redis_epoch bigint unsigned NOT NULL DEFAULT 0 COMMENT 'Redis重建栅栏代次',
 publish_operation_no varchar(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '发布稳定业务键',
 stop_reason varchar(500) NOT NULL DEFAULT '' COMMENT '停止或发布失败原因，不含秘密',
 stopped_by varchar(64) NOT NULL DEFAULT '' COMMENT '有审计的停止操作者',
 creator varchar(64) NOT NULL DEFAULT '' COMMENT '创建者',
 create_time datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC',
 updater varchar(64) NOT NULL DEFAULT '' COMMENT '修改者',
 update_time datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新UTC',
 deleted bit(1) NOT NULL DEFAULT b'0' COMMENT '仅未发布草稿可逻辑删除，业务键不复用',
 PRIMARY KEY(id), UNIQUE KEY uk_activity_no(tenant_id,activity_no),
 UNIQUE KEY uk_activity_publish(tenant_id,publish_operation_no),
 KEY idx_activity_tenant_state(tenant_id,deleted,status,start_time,id),
 KEY idx_activity_reconcile(status,end_time,id),
 CONSTRAINT ck_activity_time CHECK(start_time < end_time),
 CONSTRAINT ck_activity_limits CHECK(single_limit > 0 AND member_limit >= single_limit),
 CONSTRAINT ck_activity_status CHECK(status IN (0,10,20,30,40,50,60))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='秒杀活动';

CREATE TABLE promotion_seckill_activity_sku (
 id bigint NOT NULL AUTO_INCREMENT COMMENT '活动规格ID',
 tenant_id bigint NOT NULL COMMENT '租户',
 activity_id bigint NOT NULL COMMENT '活动逻辑ID',
 sku_id bigint NOT NULL COMMENT '商品SKU逻辑ID',
 spec_snapshot json NOT NULL COMMENT '规格展示快照',
 price_cent bigint unsigned NOT NULL COMMENT '活动单价，分',
 planned_quantity int unsigned NOT NULL COMMENT '草稿计划划拨量',
 allocated_quantity int unsigned NOT NULL DEFAULT 0 COMMENT '已实际划拨总量',
 available_quantity int unsigned NOT NULL DEFAULT 0 COMMENT '剩余量，含正在归还量',
 held_quantity int unsigned NOT NULL DEFAULT 0 COMMENT '申请和未支付订单占用',
 sold_quantity int unsigned NOT NULL DEFAULT 0 COMMENT '已支付累计，退款不减少',
 returned_quantity int unsigned NOT NULL DEFAULT 0 COMMENT '已确认归还普通库存',
 return_pending_quantity int unsigned NOT NULL DEFAULT 0 COMMENT 'available中已冻结待归还量',
 allocation_status tinyint unsigned NOT NULL DEFAULT 0 COMMENT '0未划拨10处理中20成功30归还中40已清算50待核查',
 allocation_operation_no varchar(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '当前代次划拨业务键',
 version bigint unsigned NOT NULL DEFAULT 0 COMMENT '条件更新版本',
 create_time datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建UTC',
 update_time datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新UTC',
 PRIMARY KEY(id), UNIQUE KEY uk_activity_sku(tenant_id,activity_id,sku_id),
 KEY idx_sku_conflict(tenant_id,sku_id,activity_id),
 CONSTRAINT ck_pool_price CHECK(price_cent > 0 AND planned_quantity > 0),
 CONSTRAINT ck_pool_balance CHECK(allocated_quantity = available_quantity + held_quantity + sold_quantity + returned_quantity),
 CONSTRAINT ck_pool_pending CHECK(return_pending_quantity <= available_quantity)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='秒杀权威SKU额度池';

